package auth

import (
	"log/slog"
	"time"

	"github.com/altessa-s/rmcloud-go/internal/app/retry"
	"github.com/altessa-s/rmcloud-go/internal/domain"
)

//go:generate optgen generate --string-setter plain --source-file $GOFILE

// DefaultExchangeTimeout bounds one user-token exchange, retries included.
// The exchange does not follow any caller's cancellation, so without a
// bound a server that accepts and never answers would hold it forever.
const DefaultExchangeTimeout = 2 * time.Minute

// options are a [Provider]'s tunables. The With options are generated by
// go-optgen; a nil, empty or non-positive argument keeps the default.
type options struct {
	// endpoints are the hosts the token calls go to.
	endpoints domain.Endpoints `optgen:"default=domain.Production()"`

	// policy is the retry policy. A zero policy is not substituted: a test
	// that wants no retries can ask for that on purpose.
	policy retry.Policy `optgen:"default=retry.Default()"`

	// deviceDesc is sent at registration. desktop-windows is the other label
	// this service accepts.
	deviceDesc string `optgen:"default=domain.DeviceDescMac"`

	// userAgent is the User-Agent. Empty sends no header.
	userAgent string `optgen:"manual"`

	// newID is the source of a new device id. The default is a random UUID.
	newID func() (string, error) `opt:"ID" optgen:"default=newDeviceID,notnil"`

	// exchangeTimeout bounds one user-token exchange.
	exchangeTimeout time.Duration `optgen:"default=DefaultExchangeTimeout" optval:"positive"`

	// log receives the provider's records. The default is slog.Default as it
	// stands when the provider is built.
	log *slog.Logger `opt:"Logger" optgen:"default=slog.Default()"`
}

// WithUserAgent sets the User-Agent. The empty string, a real choice, sends
// no header; go-optgen's string setter would skip it.
func WithUserAgent(ua string) Option {
	return func(o *options) { o.userAgent = ua }
}
